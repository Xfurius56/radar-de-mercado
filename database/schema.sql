create table if not exists public.settings (
    user_id uuid not null references auth.users(id) on delete cascade,
    key text not null,
    value text not null,
    primary key (user_id, key)
);

create table if not exists public.source_status (
    user_id uuid not null references auth.users(id) on delete cascade,
    source text not null,
    state text not null,
    message text not null,
    last_attempt timestamptz,
    last_success timestamptz,
    primary key (user_id, source)
);

create table if not exists public.products (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    name text not null,
    category text not null default '',
    country text not null default '',
    currency text not null default 'EUR',
    provider text not null default '',
    provider_url text not null default '',
    source_url text not null default '',
    product_cost double precision not null default 0,
    shipping_cost double precision not null default 0,
    ad_cost double precision not null default 0,
    platform_fee_pct double precision not null default 0,
    tax_pct double precision not null default 0,
    refund_pct double precision not null default 0,
    sale_price double precision not null default 0,
    launch_budget double precision not null default 0,
    delivery_days integer,
    supplier_quality double precision,
    demand_score double precision,
    demand_source text not null default '',
    demand_updated text not null default '',
    competition_score double precision,
    competitor_price double precision,
    competition_source text not null default '',
    fragile smallint not null default 0 check (fragile in (0, 1)),
    return_risk smallint not null default 0 check (return_risk in (0, 1)),
    legal_risk smallint not null default 0 check (legal_risk in (0, 1)),
    brand_risk smallint not null default 0 check (brand_risk in (0, 1)),
    notes text not null default '',
    is_favorite smallint not null default 0 check (is_favorite in (0, 1)),
    created_at timestamptz not null,
    updated_at timestamptz not null,
    unique (id, user_id)
);

create table if not exists public.watchlist (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    symbol text not null,
    asset_type text not null,
    name text not null default '',
    currency text not null default '',
    created_at timestamptz not null,
    unique (user_id, symbol, asset_type)
);

create table if not exists public.asset_observations (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    symbol text not null,
    asset_type text not null,
    name text not null default '',
    price double precision not null,
    currency text not null default '',
    change_pct double precision,
    volume double precision,
    market_cap double precision,
    volatility_pct double precision,
    avg_volume double precision,
    avg_value double precision,
    source text not null,
    source_url text not null default '',
    as_of text not null default '',
    fetched_at timestamptz not null,
    details text not null default '{}'
);

create table if not exists public.product_observations (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    product_id bigint not null,
    sale_price double precision not null,
    demand_score double precision,
    competition_score double precision,
    competitor_price double precision,
    product_cost double precision not null default 0,
    shipping_cost double precision not null default 0,
    margin_pct double precision,
    observed_at timestamptz not null,
    foreign key (product_id, user_id) references public.products(id, user_id) on delete cascade
);

create table if not exists public.alerts (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    kind text not null,
    target text not null,
    operator text not null,
    threshold double precision not null,
    label text not null default '',
    active boolean not null default true,
    status text not null default 'pendiente',
    created_at timestamptz not null,
    triggered_at timestamptz,
    last_checked timestamptz,
    details text not null default ''
