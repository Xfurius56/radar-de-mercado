create table if not exists public.lesson_progress (
    user_id uuid not null references auth.users(id) on delete cascade,
    lesson_id text not null,
    completed boolean not null default false,
    quiz_score double precision,
    updated_at timestamptz not null,
    primary key (user_id, lesson_id)
);

create table if not exists public.image_analyses (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    mode text not null check (mode in ('Dropshipping', 'Trading')),
    file_name text not null,
    analysis text not null default '',
    status text not null default 'procesando' check (status in ('procesando', 'completado', 'error')),
    created_at timestamptz not null
);

-- Row Level Security protege también ante una consulta mal filtrada en la aplicación.
do $$
declare target_table text;
        sequence_name text;
begin
    foreach target_table in array array[
        'settings', 'source_status', 'products', 'watchlist', 'asset_observations',
        'product_observations', 'alerts', 'portfolios', 'sim_trades',
        'portfolio_marks', 'lesson_progress', 'image_analyses'
    ] loop
        execute format('alter table public.%I enable row level security', target_table);
        execute format('revoke all on table public.%I from anon, public', target_table);
        execute format('grant select, insert, update, delete on table public.%I to authenticated', target_table);
        execute format('drop policy if exists user_owns_rows on public.%I', target_table);
        execute format(
            'create policy user_owns_rows on public.%I for all to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id)',
            target_table
        );
        if exists (
            select 1
            from information_schema.columns c
            where c.table_schema = 'public'
              and c.table_name = target_table
              and c.column_name = 'id'
        ) then
            sequence_name := pg_get_serial_sequence(format('public.%I', target_table), 'id');
            if sequence_name is not null then
                execute format('grant usage, select on sequence %s to authenticated', sequence_name);
            end if;
        end if;
    end loop;
end $$;

grant usage on schema public to authenticated;

create index if not exists products_owner_created_idx on public.products(user_id, created_at desc);
create index if not exists observations_owner_symbol_idx on public.asset_observations(user_id, symbol, asset_type, fetched_at desc);
create index if not exists product_observations_owner_product_idx on public.product_observations(user_id, product_id, observed_at);
create index if not exists alerts_owner_created_idx on public.alerts(user_id, created_at desc);
create index if not exists image_analyses_owner_created_idx on public.image_analyses(user_id, created_at desc);
